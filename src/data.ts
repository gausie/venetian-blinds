// $F2CE: GRP1 (quad width player 1) graphics for the scene, same indexing
export const SCENE_GFX: number[] = (() => {
  const gfx = Array<number>(177).fill(0xff);
  gfx.splice(94, 5, 0x00, 0x00, 0x80, 0xc4, 0xee);
  return gfx;
})();

