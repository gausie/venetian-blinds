// Tables lifted from the original 2K ROM. Kernel tables are indexed by the
// scanline counter, which counts *down* from 176 at the top of the window.

const runs = (spec: [value: number, count: number][]): number[] =>
  spec.flatMap(([value, count]) => Array<number>(count).fill(value));

